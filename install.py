#!/usr/bin/env python3
"""
Universal Installer for MyCode - Works on Linux, macOS, and Windows
====================================================================
Run: python install.py

What it does:
  1. Checks Python version (needs 3.9+)
  2. Installs the 'openai' Python package
  3. Copies mycode package to user's home directory
  4. Creates a 'mycode' command in PATH:
     - Linux/macOS: ~/.local/bin/mycode (shell wrapper)
     - Windows: %USERPROFILE%\\.mycode\\bin\\mycode.bat (batch wrapper)
  5. Tells you how to refresh PATH (if needed)
  6. Runs a smoke test to verify 'mycode --version' works

After install, just type `mycode` from ANY directory and the CLI opens.
"""

import os
import sys
import shutil
import subprocess
from pathlib import Path

# === ANSI colors (work on most terminals) ===
IS_WIN = os.name == "nt"

def c(text, color):
    """Colorize text for terminal."""
    if IS_WIN and not os.environ.get("WT_SESSION"):
        return text  # Skip colors on basic Windows cmd
    codes = {
        "red": "\033[91m", "green": "\033[92m", "yellow": "\033[93m",
        "blue": "\033[94m", "magenta": "\033[95m", "cyan": "\033[96m",
        "bold": "\033[1m", "reset": "\033[0m"
    }
    return f"{codes.get(color, '')}{text}{codes['reset']}"

def info(msg):  print(c(f"[INFO]  {msg}", "cyan"))
def ok(msg):    print(c(f"[OK]    {msg}", "green"))
def warn(msg):  print(c(f"[WARN]  {msg}", "yellow"))
def err(msg):   print(c(f"[ERR]   {msg}", "red"))
def head(msg):  print(c(f"\n=== {msg} ===", "bold"))


# === Step 1: Check Python ===
def check_python():
    head("Step 1: Check Python")
    if sys.version_info < (3, 9):
        err(f"Python 3.9+ required, you have {sys.version.split()[0]}")
        err("Download from: https://python.org/downloads")
        sys.exit(1)
    ok(f"Python {sys.version.split()[0]} detected")
    info(f"Interpreter: {sys.executable}")


# === Step 2: Install openai package ===
def install_deps():
    head("Step 2: Install dependencies")
    info("Installing 'openai' package...")
    try:
        subprocess.check_call(
            [sys.executable, "-m", "pip", "install", "--user", "--quiet",
             "openai>=1.50.0"],
            stdout=subprocess.DEVNULL
        )
        ok("openai package installed")
    except subprocess.CalledProcessError:
        warn("--user install failed, trying system-wide...")
        try:
            subprocess.check_call(
                [sys.executable, "-m", "pip", "install", "--quiet",
                 "openai>=1.50.0"],
                stdout=subprocess.DEVNULL
            )
            ok("openai package installed (system)")
        except subprocess.CalledProcessError as e:
            err(f"Failed to install openai: {e}")
            err("Try manually: pip install openai")
            sys.exit(1)


# === Step 3: Install mycode package ===
def install_mycode_package():
    head("Step 3: Install MyCode package")
    info("Running: pip install -e . (editable install)")
    try:
        subprocess.check_call(
            [sys.executable, "-m", "pip", "install", "-e", ".", "--quiet"],
            stdout=subprocess.DEVNULL
        )
        ok("MyCode package installed")
    except subprocess.CalledProcessError as e:
        err(f"Install failed: {e}")
        err("Try manually: pip install -e .")
        sys.exit(1)


# === Step 4: Create wrapper script in PATH ===
def install_wrapper():
    """Create a 'mycode' wrapper script in a directory that's in PATH."""
    head("Step 4: Create 'mycode' command wrapper")

    python_exe = sys.executable
    # Normalize path (handle spaces, slashes)
    if IS_WIN:
        python_exe = python_exe.replace("/", "\\")
    else:
        python_exe = python_exe.replace("\\", "/")

    if IS_WIN:
        # === WINDOWS ===
        # Install to %USERPROFILE%\.mycode\bin\mycode.bat
        bin_dir = Path.home() / ".mycode" / "bin"
        bin_dir.mkdir(parents=True, exist_ok=True)
        wrapper_path = bin_dir / "mycode.bat"

        wrapper_content = f"""@echo off
REM MyCode CLI wrapper - generated by install.py
"{python_exe}" -m mycode %*
"""
        wrapper_path.write_text(wrapper_content, encoding="utf-8")
        ok(f"Wrapper created: {wrapper_path}")

        # Add to user PATH (persistent)
        add_to_path_windows(bin_dir)
        return wrapper_path

    else:
        # === LINUX / macOS ===
        # Try ~/.local/bin first (standard user bin), fall back to ~/bin
        candidates = [Path.home() / ".local" / "bin", Path.home() / "bin"]
        bin_dir = None
        for c_dir in candidates:
            c_dir.mkdir(parents=True, exist_ok=True)
            bin_dir = c_dir
            break

        wrapper_path = bin_dir / "mycode"

        wrapper_content = f"""#!/usr/bin/env bash
# MyCode CLI wrapper - generated by install.py
exec "{python_exe}" -m mycode "$@"
"""
        wrapper_path.write_text(wrapper_content, encoding="utf-8")
        wrapper_path.chmod(0o755)  # make executable
        ok(f"Wrapper created: {wrapper_path}")

        # Check if bin_dir is in PATH; if not, add to shell rc
        if str(bin_dir) not in os.environ.get("PATH", ""):
            add_to_path_unix(bin_dir)
        else:
            ok(f"{bin_dir} is already in PATH")

        return wrapper_path


def add_to_path_windows(bin_dir):
    """Add directory to user PATH on Windows (persistent)."""
    try:
        import winreg
        key = winreg.OpenKey(
            winreg.HKEY_CURRENT_USER, "Environment",
            0, winreg.KEY_READ | winreg.KEY_WRITE
        )
        try:
            path_val, _ = winreg.QueryValueEx(key, "PATH")
        except FileNotFoundError:
            path_val = ""

        bin_str = str(bin_dir)
        if bin_str.lower() not in path_val.lower():
            new_path = path_val.rstrip(";") + ";" + bin_str if path_val else bin_str
            winreg.SetValueEx(key, "PATH", 0, winreg.REG_EXPAND_SZ, new_path)
            ok(f"Added to user PATH: {bin_str}")
            warn("Please OPEN A NEW TERMINAL for PATH changes to take effect.")
        else:
            ok(f"{bin_str} already in user PATH")
        winreg.CloseKey(key)
    except Exception as e:
        warn(f"Could not auto-add to PATH: {e}")
        warn(f"Manually add this to your PATH: {bin_dir}")
        warn("  Settings > System > About > Advanced > Environment Variables")


def add_to_path_unix(bin_dir):
    """Add directory to PATH in shell rc file (bash/zsh)."""
    shell = os.environ.get("SHELL", "")
    home = Path.home()
    added_to = []

    # Detect shell rc files
    rc_files = []
    if "zsh" in shell:
        rc_files = [home / ".zshrc"]
    elif "bash" in shell:
        rc_files = [home / ".bashrc"]
        if (home / ".bash_profile").exists():
            rc_files.append(home / ".bash_profile")
    else:
        # Try both
        rc_files = [home / ".bashrc", home / ".zshrc"]

    # Filter to only existing files (or default to .bashrc)
    rc_files = [f for f in rc_files if f.exists()] or [home / ".bashrc"]

    export_line = f'\nexport PATH="{bin_dir}:$PATH"  # Added by MyCode installer\n'

    for rc in rc_files:
        try:
            content = rc.read_text(encoding="utf-8") if rc.exists() else ""
            if str(bin_dir) not in content:
                with open(rc, "a", encoding="utf-8") as f:
                    f.write(export_line)
                ok(f"Added PATH export to {rc}")
                added_to.append(rc)
            else:
                ok(f"{rc} already has {bin_dir} in PATH")
        except Exception as e:
            warn(f"Could not update {rc}: {e}")

    if added_to:
        warn(f"To use 'mycode' now, run: source {added_to[0]}")
        warn("Or open a new terminal.")


# === Step 5: Smoke test ===
def smoke_test():
    head("Step 5: Smoke test")
    info("Testing 'mycode --version'...")

    # Use the python directly to test (avoid PATH issues in same session)
    test_cmd = [sys.executable, "-m", "mycode", "--version"]
    try:
        result = subprocess.run(
            test_cmd, capture_output=True, text=True, timeout=10
        )
        if result.returncode == 0:
            ok(f"mycode runs: {result.stdout.strip()}")
        else:
            err(f"mycode failed: {result.stderr.strip()}")
            return False
    except Exception as e:
        err(f"Test error: {e}")
        return False

    # Test provider list (should work without API keys)
    info("Testing 'mycode provider list'...")
    try:
        result = subprocess.run(
            [sys.executable, "-m", "mycode", "provider", "list"],
            capture_output=True, text=True, timeout=10
        )
        if result.returncode == 0 and "groq" in result.stdout.lower():
            ok("provider list works (Groq/Gemini/etc. visible)")
        else:
            warn("provider list had issues, but core CLI works")
    except Exception:
        pass

    return True


# === Final summary ===
def print_summary(wrapper_path):
    head("Install Complete!")
    print()
    print(c("  ╔══════════════════════════════════════════════════════╗", "green"))
    print(c("  ║  MyCode is now installed!                            ║", "green"))
    print(c("  ║                                                      ║", "green"))
    print(c("  ║  Open a NEW terminal, then run:                      ║", "green"))
    print(c("  ║                                                      ║", "green"))
    print(c("  ║     mycode                                           ║", "bold"))
    print(c("  ║                                                      ║", "green"))
    print(c("  ║  Or use commands directly:                           ║", "green"))
    print(c("  ║     mycode chat \"hello\"                              ║", "green"))
    print(c("  ║     mycode agent \"build a calculator\"                 ║", "green"))
    print(c("  ║     mycode provider list                              ║", "green"))
    print(c("  ║     mycode provider add-key groq                     ║", "green"))
    print(c("  ║     mycode prompts edit planner                      ║", "green"))
    print(c("  ╚══════════════════════════════════════════════════════╝", "green"))
    print()
    info(f"Wrapper: {wrapper_path}")
    if IS_WIN:
        warn("NOTE: Close this terminal and open a new one for PATH to refresh.")
    else:
        warn("NOTE: Run 'source ~/.bashrc' (or open new terminal) to use 'mycode' now.")
    print()
    print(c("  Get free Groq API key: https://console.groq.com/keys", "cyan"))
    print(c("  Then: mycode provider add-key groq", "cyan"))
    print()


# === Main ===
def main():
    print()
    print(c("  ╔══════════════════════════════════════════════════╗", "cyan"))
    print(c("  ║   MyCode Universal Installer                      ║", "cyan"))
    print(c("  ║   Works on Linux, macOS, and Windows             ║", "cyan"))
    print(c("  ╚══════════════════════════════════════════════════╝", "cyan"))
    print()

    # Make sure we're in the right directory (script should be next to setup.py)
    script_dir = Path(__file__).parent.resolve()
    setup_py = script_dir / "setup.py"
    if not setup_py.exists():
        err(f"setup.py not found in {script_dir}")
        err("Run this installer from the mycode project directory.")
        sys.exit(1)
    os.chdir(script_dir)
    info(f"Working directory: {script_dir}")

    check_python()
    install_deps()
    install_mycode_package()
    wrapper_path = install_wrapper()
    smoke_test()
    print_summary(wrapper_path)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print(c("\n\nInstall cancelled by user.", "yellow"))
        sys.exit(1)
